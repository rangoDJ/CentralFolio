export interface CalendarDividendEvent {
  symbol: string;
  name?: string;
  amount: number;
  date: string; // YYYY-MM-DD pay date
  exDate?: string;
  amountPerShare?: number;
  units?: number;
  currency?: string;
  isConfirmed?: boolean;
}

function formatDateToIcs(dateStr: string): string {
  // Return YYYYMMDD
  return dateStr.replace(/[^0-9]/g, '').slice(0, 8);
}

function formatNowStamp(): string {
  return new Date().toISOString().replace(/[-:]/g, '').slice(0, 15) + 'Z';
}

function escapeIcsText(str: string): string {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\n/g, '\\n');
}

export function generateIcsCalendar(
  events: CalendarDividendEvent[],
  calendarName = 'CentralFolio Dividend Calendar'
): string {
  const dtStamp = formatNowStamp();
  const lines: string[] = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//CentralFolio//Dividend Calendar//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    `X-WR-CALNAME:${escapeIcsText(calendarName)}`,
    'X-WR-TIMEZONE:UTC',
  ];

  for (const ev of events) {
    if (!ev.date) continue;
    const dStart = formatDateToIcs(ev.date);
    if (dStart.length !== 8) continue;

    const cur = ev.currency || 'USD';
    const confTag = ev.isConfirmed ? '' : ' [Estimated]';
    const summary = `💰 ${ev.symbol} Dividend ($${ev.amount.toFixed(2)} ${cur})${confTag}`;
    const uid = `div-${ev.symbol.toLowerCase()}-${dStart}-${Math.round(ev.amount * 100)}@centralfolio`;

    const descParts: string[] = [
      `${ev.name || ev.symbol} Dividend Payout: $${(ev.amountPerShare || 0).toFixed(4)}/share`,
    ];
    if (ev.units != null) descParts.push(`Holding: ${ev.units.toLocaleString()} shares`);
    if (ev.exDate) descParts.push(`Ex-Dividend Date: ${ev.exDate}`);
    descParts.push(`Status: ${ev.isConfirmed ? 'Confirmed Announcement' : 'Estimated Forecast'}`);
    descParts.push('Generated by CentralFolio');

    lines.push('BEGIN:VEVENT');
    lines.push(`UID:${uid}`);
    lines.push(`DTSTAMP:${dtStamp}`);
    lines.push(`DTSTART;VALUE=DATE:${dStart}`);
    lines.push(`SUMMARY:${escapeIcsText(summary)}`);
    lines.push(`DESCRIPTION:${escapeIcsText(descParts.join('\\n'))}`);
    lines.push(`STATUS:${ev.isConfirmed ? 'CONFIRMED' : 'TENTATIVE'}`);
    lines.push('TRANSP:TRANSPARENT');
    lines.push('END:VEVENT');
  }

  lines.push('END:VCALENDAR');
  return lines.join('\r\n');
}
